import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { truncateHead } from "@earendil-works/pi-coding-agent";

export async function prepareOutput(
  output: string,
  kind: "fetch" | "search",
  signal?: AbortSignal,
) {
  signal?.throwIfAborted();
  const preview = truncateHead(output);
  let fullOutputPath: string | undefined;
  let text = preview.content;
  if (preview.truncated) {
    const directory = await mkdtemp(join(tmpdir(), `pi-web-${kind}-`));
    fullOutputPath = join(directory, "content.txt");
    try {
      await writeFile(fullOutputPath, output, {
        encoding: "utf8",
        mode: 0o600,
        ...(signal ? { signal } : {}),
      });
      signal?.throwIfAborted();
    } catch (error) {
      await rm(directory, { recursive: true, force: true });
      throw error;
    }
    const label = kind === "fetch" ? "Full extracted text" : "Full search results";
    text += `\n\n[Output truncated. ${label} saved to: ${fullOutputPath}. Use read with offset/limit to continue.]`;
  }
  return {
    content: [{ type: "text" as const, text }],
    details: {
      truncated: preview.truncated,
      ...(fullOutputPath ? { fullOutputPath } : {}),
    },
  };
}
